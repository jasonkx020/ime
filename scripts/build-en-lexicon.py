def main() -> None:
    rows: dict[str, int] = {}
    for word, freq in IME_BOOST:
        key = word.strip()
        if not key:
            continue
        roman = key.lower().replace("'", "")
        # Keep display form; lookup key is lowercase ascii
        prev = rows.get(key.lower(), 0)
        if freq > prev:
            rows[key.lower()] = freq

    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = ["word\tfreq\tromanced"]
    # Use romanized column name expected by compile: pinyin OR third col
    lines = ["word\tfreq\tpinyin"]
    for word, freq in sorted(rows.items(), key=lambda x: (-x[1], x[0])):
        lines.append(f"{word}\t{freq}\t{word}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} words → {OUT}")


if __name__ == "__main__":
    main()
